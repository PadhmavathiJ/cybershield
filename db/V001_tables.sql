CREATE TABLE app_user (
    user_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    email VARCHAR2(254 CHAR) NOT NULL,
    password_hash VARCHAR2(255 CHAR) NOT NULL,
    full_name VARCHAR2(120 CHAR) NOT NULL,
    role_code VARCHAR2(10 CHAR) NOT NULL,
    is_active NUMBER(1) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_app_user PRIMARY KEY (user_id)
);

CREATE TABLE investigator (
    investigator_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    user_id NUMBER(10) NOT NULL,
    specialization VARCHAR2(120 CHAR) NOT NULL,
    availability VARCHAR2(12 CHAR) DEFAULT 'AVAILABLE' NOT NULL,
    CONSTRAINT pk_investigator PRIMARY KEY (investigator_id)
);

CREATE TABLE ip_address (
    ip_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ip_text VARCHAR2(45 CHAR) NOT NULL,
    country_code VARCHAR2(2 CHAR),
    is_simulated NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT pk_ip_address PRIMARY KEY (ip_id)
);

CREATE TABLE server (
    server_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    hostname VARCHAR2(120 CHAR) NOT NULL,
    os_name VARCHAR2(100 CHAR) NOT NULL,
    department VARCHAR2(100 CHAR) NOT NULL,
    criticality VARCHAR2(8 CHAR) DEFAULT 'MEDIUM' NOT NULL,
    is_active NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT pk_server PRIMARY KEY (server_id)
);

CREATE TABLE server_ip_address (
    server_ip_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    server_id NUMBER(10) NOT NULL,
    ip_id NUMBER(10) NOT NULL,
    valid_from TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    valid_to TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_server_ip_address PRIMARY KEY (server_ip_id)
);

CREATE TABLE attack_type (
    attack_type_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
