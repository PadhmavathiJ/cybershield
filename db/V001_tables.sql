    CONSTRAINT pk_attack_campaign PRIMARY KEY (campaign_id)
);

CREATE TABLE soc_policy (
    policy_key VARCHAR2(40 CHAR) NOT NULL,
    number_value NUMBER(10,2) NOT NULL,
    description VARCHAR2(200 CHAR) NOT NULL,
    CONSTRAINT pk_soc_policy PRIMARY KEY (policy_key)
);

CREATE TABLE security_event (
    event_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    source_event_key VARCHAR2(100 CHAR) NOT NULL,
    server_id NUMBER(10) NOT NULL,
    source_ip_id NUMBER(10) NOT NULL,
    attack_type_id NUMBER(10) NOT NULL,
    event_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    protocol VARCHAR2(16 CHAR) NOT NULL,
    packet_count NUMBER(18) DEFAULT 0 NOT NULL,
    bytes_in NUMBER(18) DEFAULT 0 NOT NULL,
    bytes_out NUMBER(18) DEFAULT 0 NOT NULL,
    severity_score NUMBER(5,2) NOT NULL,
    details CLOB,
    is_simulated NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT pk_security_event PRIMARY KEY (event_id)
);

CREATE TABLE alert (
    alert_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    event_id NUMBER(10) NOT NULL,
    severity VARCHAR2(8 CHAR) NOT NULL,
    status VARCHAR2(12 CHAR) DEFAULT 'NEW' NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    acknowledged_at TIMESTAMP WITH TIME ZONE,
